export function getRussianHolidayInfo(dateStr: string): RussianHolidayInfo {
  const mmdd = dateStr.slice(5); // YYYY-MM-DD -> MM-DD

  // 1. Официальные нерабочие праздничные дни (ст. 112 ТК РФ) — всегда двойная оплата при выходе на смену
  if (STATUTORY_HOLIDAYS_MMDD[mmdd]) {
    const holiday = STATUTORY_HOLIDAYS_MMDD[mmdd];
    return {
      isHoliday: true,
      isDoublePayEligible: true,
      name: holiday.name,
      fullName: holiday.fullName,
      description: holiday.description,
      category: 'statutory',
    };
  }

  // 2. Дни переносов по Постановлениям Правительства РФ
  if (GOVERNMENT_TRANSFERS[dateStr]) {
    const transfer = GOVERNMENT_TRANSFERS[dateStr];
    return {
      isHoliday: true,
      isDoublePayEligible: false, // При сменном графике переносы выходных не дают двойную оплату, если день не в ст. 112
      name: transfer.name,
      fullName: transfer.fullName,
      description: transfer.description,
      category: 'transfer',
    };
  }

  return {
    isHoliday: false,
    isDoublePayEligible: false,
  };
}
