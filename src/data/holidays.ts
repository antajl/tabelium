/**
 * Производственный календарь РФ (ст. 112 Трудового кодекса РФ).
 * Официальные нерабочие праздничные дни, работа в которые по ст. 153 ТК РФ
 * подлежит оплате не менее чем в двойном размере (2x).
 */

export interface RussianHoliday {
  date: string; // YYYY-MM-DD
  name: string;
  isStatutory: boolean; // Официальный нерабочий праздничный день по ст. 112 ТК РФ
  comment?: string;
}

// Стандартные ежегодные праздничные дни по ст. 112 ТК РФ (месяц-день: MM-DD)
export const STATUTORY_HOLIDAYS_MMDD: Record<string, string> = {
  '01-01': 'Новогодние каникулы',
  '01-02': 'Новогодние каникулы',
  '01-03': 'Новогодние каникулы',
  '01-04': 'Новогодние каникулы',
  '01-05': 'Новогодние каникулы',
  '01-06': 'Новогодние каникулы',
  '01-07': 'Рождество Христово',
  '01-08': 'Новогодние каникулы',
  '02-23': 'День защитника Отечества',
  '03-08': 'Международный женский день',
  '05-01': 'Праздник Весны и Труда',
  '05-09': 'День Победы',
  '06-12': 'День России',
  '11-04': 'День народного единства',
};

// Дополнительные официальные выходные/переносы по Постановлениям Правительства РФ
export const GOVERNMENT_TRANSFERS: Record<string, string> = {
  // 2025 год
  '2025-05-02': 'Перенос выходного (майские)',
  '2025-05-08': 'Перенос выходного (майские)',
  '2025-06-13': 'Перенос выходного (День России)',
  '2025-11-03': 'Перенос выходного (День народного единства)',
  '2025-12-31': 'Перенос выходного (предпраздничный)',
  
  // 2026 год
  '2026-05-04': 'Перенос выходного (майские)',
  '2026-05-11': 'Перенос выходного (День Победы)',
  '2026-12-31': 'Выходной день',
};

export function getRussianHolidayInfo(dateStr: string): {
  isHoliday: boolean;
  isDoublePayEligible: boolean; // Оплата в двойном размере (ст. 153 ТК РФ)
  name?: string;
} {
  const mmdd = dateStr.slice(5); // YYYY-MM-DD -> MM-DD
  
  // 1. Официальные нерабочие праздничные дни (ст. 112 ТК РФ) — всегда двойная оплата при выходе на смену
  if (STATUTORY_HOLIDAYS_MMDD[mmdd]) {
    return {
      isHoliday: true,
      isDoublePayEligible: true,
      name: STATUTORY_HOLIDAYS_MMDD[mmdd],
    };
  }

  // 2. Дни переносов по постановлению правительства
  if (GOVERNMENT_TRANSFERS[dateStr]) {
    return {
      isHoliday: true,
      isDoublePayEligible: false, // При сменном графике переносы выходных не дают двойную оплату, если день не в ст. 112
      name: GOVERNMENT_TRANSFERS[dateStr],
    };
  }

  return {
    isHoliday: false,
    isDoublePayEligible: false,
  };
}
